//! Game Builder: turn solo options into a player YAML for the Archipela-Go 2 apworld.

use crate::goal::goal_yaml_name;
use crate::num::count_u32;
use crate::slot::{check_goal_specs, GoalMode};
use crate::solo::SoloOptions;

/// The game name registered by the apworld.
pub const GAME_NAME: &str = "Archipela-Go 2: Electric Boogaloo";

fn list(v: &[String]) -> String {
    format!("[{}]", v.join(", "))
}

/// Archipelago player YAML for `player_name` built from the solo `o` options.
///
/// # Errors
/// Returns the reason if the goals cannot be played (unknown, repeated, or an impossible "at least N").
pub fn build_yaml(player_name: &str, o: &SoloOptions) -> Result<String, String> {
    let modes: Vec<String> = o.zone_modes.iter().map(|m| m.name().to_string()).collect();
    let b = |x: bool| if x { "true" } else { "false" };
    let goals = o.goal_list();
    check_goal_specs(&goals, o.goal_mode, o.goal_need)?;
    let selection: Vec<String> = goals.iter().map(|g| goal_yaml_name(&g.id).to_string()).collect();
    let (requirement, need) = match o.goal_mode {
        GoalMode::Any => ("require_any_one_goal", 1),
        GoalMode::All => ("require_all_goals", count_u32(goals.len())),
        GoalMode::AtLeast => ("require_at_least_n_goals", o.goal_need),
    };
    // The apworld has one list of quest types for the whole game: a game with per-zone lists exports their union.
    let mut quest_types: Vec<String> = Vec::new();
    for t in o.zone_quest_types.iter().flatten().chain(if o.zone_quest_types.iter().any(|z| !z.is_empty()) { [].iter() } else { o.quest_types.iter() }) {
        if !quest_types.contains(t) {
            quest_types.push(t.clone());
        }
    }
    Ok(format!(
        "name: {name}\ngame: \"{game}\"\ndescription: Generated by the Archipela-Go 2 app\n\"{game}\":\n  goal_selection: {gs}\n  goal_requirement: {req}\n  goals_required: {need}\n  number_of_trips: {n}\n  zone_modes: {zm}\n  easy_share: {e}\n  medium_share: {m}\n  hard_share: {h}\n  minutes_per_tier: {mpt}\n  minimum_distance: {md}\n  quest_types: {qt}\n  enabled_traps: {et}\n  trap_rate: {tr}\n  enable_effort_reductions: {er}\n  enable_scouting_distance_bonuses: {sc}\n  enable_collection_distance_bonuses: {co}\n  reduction_percent: {rp}\n  fog_of_war: {fog}\n  return_home: {rh}\n  death_link: false\n",
        name = player_name,
        game = GAME_NAME,
        gs = list(&selection),
        req = requirement,
        need = need,
        n = o.number_of_trips,
        zm = list(&modes),
        e = o.easy_share,
        m = o.medium_share,
        h = o.hard_share,
        mpt = o.minutes_per_tier,
        md = o.min_distance_m,
        qt = list(&quest_types),
        et = list(&o.enabled_traps),
        tr = o.trap_rate,
        er = b(o.enable_effort_reductions),
        sc = b(o.enable_scouting),
        co = b(o.enable_collection),
        rp = o.reduction_percent,
        fog = b(o.fog_of_war),
        rh = b(o.return_home),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::Mode;
    use crate::slot::{GoalMode, GoalSpec};

    #[test]
    fn yaml_has_every_option_key_the_apworld_example_uses() {
        let example = include_str!("../../apworld/docs/example.yaml");
        let ours = build_yaml("Tester", &SoloOptions::default()).unwrap();
        for line in example.lines() {
            let t = line.trim();
            if t.starts_with('#') || !t.contains(':') || t.starts_with("name") || t.starts_with("game") || t.starts_with("description") || t.starts_with('"') {
                continue;
            }
            let key = t.split(':').next().unwrap();
            assert!(ours.contains(&format!("  {key}:")), "our YAML is missing option `{key}` that the apworld example uses");
        }
    }

    #[test]
    fn modes_and_lists_are_rendered_for_the_apworld() {
        let o = SoloOptions { zone_modes: vec![Mode::Walk, Mode::Bike, Mode::Drive], goal: "treasure_hunt".into(), ..SoloOptions::default() };
        let y = build_yaml("Me", &o).unwrap();
        assert!(y.contains("zone_modes: [walk, bike, drive]") && y.contains("goal_selection: [Treasure Hunt]") && y.contains("name: Me"));
        assert!(y.contains("enable_effort_reductions: false"));
    }

    #[test]
    fn each_goal_requirement_uses_the_apworlds_name() {
        let g = |id: &str| GoalSpec { id: id.into(), target: 0 };
        let with = |mode| {
            build_yaml("Me", &SoloOptions { goals: vec![g("treasure_hunt"), g("all_trips")], goal_mode: mode, goal_need: 2, ..SoloOptions::default() }).unwrap()
        };
        assert!(with(GoalMode::AtLeast).contains("goal_requirement: require_at_least_n_goals"));
        assert!(with(GoalMode::Any).contains("goal_requirement: require_any_one_goal"));
        assert!(with(GoalMode::All).contains("goal_requirement: require_all_goals"));
    }

    #[test]
    fn yaml_names_only_the_two_goals_and_no_target_options() {
        let y = build_yaml("Me", &SoloOptions::default()).unwrap();
        assert!(y.contains("goal_selection: [Treasure Hunt]"), "{y}");
        assert!(!y.contains("goal_streak_days") && !y.contains("goal_quest_dex_kinds"), "{y}");
    }

    #[test]
    fn goals_required_is_the_number_the_rule_needs() {
        let g = |id: &str| GoalSpec { id: id.into(), target: 0 };
        let both = |mode, need| SoloOptions { goals: vec![g("treasure_hunt"), g("all_trips")], goal_mode: mode, goal_need: need, ..SoloOptions::default() };
        assert!(build_yaml("Me", &SoloOptions::default()).unwrap().contains("goals_required: 1"), "one goal needs one");
        assert!(build_yaml("Me", &both(GoalMode::Any, 0)).unwrap().contains("goals_required: 1"));
        assert!(build_yaml("Me", &both(GoalMode::All, 0)).unwrap().contains("goals_required: 2"));
        assert!(build_yaml("Me", &both(GoalMode::AtLeast, 2)).unwrap().contains("goals_required: 2"));
    }

    #[test]
    fn an_impossible_goal_count_is_an_error_not_a_quiet_fix() {
        let g = |id: &str| GoalSpec { id: id.into(), target: 0 };
        let o = SoloOptions { goals: vec![g("treasure_hunt"), g("all_trips")], goal_mode: GoalMode::AtLeast, goal_need: 5, ..SoloOptions::default() };
        let err = build_yaml("Me", &o).unwrap_err();
        assert!(err.contains("at least 5"), "{err}");
        let removed = SoloOptions { goals: vec![g("boss")], ..SoloOptions::default() };
        assert!(build_yaml("Me", &removed).unwrap_err().contains("unknown goal"));
    }

    #[test]
    fn per_zone_quest_types_are_exported_as_one_union() {
        let o = SoloOptions {
            quest_types: vec!["reach".into()],
            zone_quest_types: vec![vec!["park".into()], vec!["dwell".into(), "park".into()]],
            ..SoloOptions::default()
        };
        let y = build_yaml("Me", &o).unwrap();
        assert!(y.contains("quest_types: [park, dwell]"), "{y}");
    }
}
